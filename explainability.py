import numpy as np
import torch
from PIL import Image
from matplotlib import cm


def _overlay_heatmap(
    image: Image.Image, heatmap: np.ndarray, alpha: float = 0.45
):
    """Blend a normalized (0-1) HxW heatmap onto a PIL image via jet cmap."""
    heatmap_img = Image.fromarray(
        (cm.jet(heatmap)[:, :, :3] * 255).astype(np.uint8)
    ).resize(image.size, resample=Image.BILINEAR)

    base = np.array(image).astype(np.float32)
    overlay = np.array(heatmap_img).astype(np.float32)
    blended = (1 - alpha) * base + alpha * overlay
    return Image.fromarray(blended.astype(np.uint8))


# ============================================================
# GRAD-CAM
# ============================================================

def generate_gradcam(
    model, image: Image.Image, input_tensor: torch.Tensor,
    target_layer, target_class: int = None
):
    """
    Compute a Grad-CAM heatmap overlay for a single image.

    Args:
        model: the classification model (in eval mode)
        image: original PIL image (used only for size/blending)
        input_tensor: preprocessed input tensor, shape (1, C, H, W)
        target_layer: the conv layer to hook (e.g. model.backbone.layer4[-1])
        target_class: class index to explain; defaults to the predicted class

    Returns:
        (overlay_image, target_class): PIL.Image and the explained class index
    """
    activations = {}
    gradients = {}

    def forward_hook(module, inputs, output):
        activations["value"] = output.detach()

    def backward_hook(module, grad_input, grad_output):
        gradients["value"] = grad_output[0].detach()

    handle_f = target_layer.register_forward_hook(forward_hook)
    handle_b = target_layer.register_full_backward_hook(backward_hook)

    try:
        model.zero_grad()
        output = model(input_tensor)

        if target_class is None:
            target_class = int(output.argmax(dim=1).item())

        score = output[0, target_class]
        score.backward()

        acts = activations["value"][0]
        grads = gradients["value"][0]
    finally:
        handle_f.remove()
        handle_b.remove()

    weights = grads.mean(dim=(1, 2))
    cam = torch.relu((weights[:, None, None] * acts).sum(dim=0))

    cam -= cam.min()
    if cam.max() > 0:
        cam /= cam.max()

    overlay = _overlay_heatmap(image, cam.cpu().numpy())
    return overlay, target_class


# ============================================================
# SHAP
# ============================================================

def generate_shap_analysis(
    model, image: Image.Image, input_tensor: torch.Tensor,
    device, class_labels, target_class: int = None,
    n_background: int = 8, n_samples: int = 50
):
    """
    Compute SHAP (GradientExplainer) values for every class in one pass.

    Background samples are generated by adding small Gaussian noise to the
    input image itself, since no training dataset is available at inference
    time. This is a common lightweight approximation for demo purposes.

    Args:
        class_labels: ordered list of class codes, index == model output index

    Returns:
        overlay: PIL.Image heatmap overlay for `target_class`
        target_class: the explained class index
        class_scores: dict {class_code: net SHAP contribution} for every class
            (positive = supports that class, negative = argues against it)
    """
    import shap

    background = input_tensor.repeat(n_background, 1, 1, 1)
    background = background + torch.randn_like(background) * 0.15
    background = background.to(device)

    explainer = shap.GradientExplainer(model, background)
    shap_values = explainer.shap_values(
        input_tensor.to(device), nsamples=n_samples
    )

    if target_class is None:
        with torch.no_grad():
            logits = model(input_tensor.to(device))
        target_class = int(logits.argmax(dim=1).item())

    if isinstance(shap_values, list):
        # one (1, C, H, W) array per class
        per_class = [v[0] for v in shap_values]
    else:
        # single (1, C, H, W, num_classes) array
        per_class = [shap_values[0, ..., i] for i in range(len(class_labels))]

    values = per_class[target_class]
    heatmap = np.abs(values).sum(axis=0)

    heatmap -= heatmap.min()
    if heatmap.max() > 0:
        heatmap /= heatmap.max()

    overlay = _overlay_heatmap(image, heatmap)

    class_scores = {
        class_labels[i]: float(per_class[i].sum())
        for i in range(len(class_labels))
    }

    return overlay, target_class, class_scores
